/**
 * Bulk import / manual entry (convex/imports.ts). The server is the authority:
 * preview and commit run the same validation; a commit with any invalid row
 * writes nothing.
 */
import { describe, expect, test } from "vitest";
import { api } from "../../convex/_generated/api";
import { as, createSchool, errorCode, makeTest, type T } from "./fixtures";
import { STUDENT_IMPORT, TEACHER_IMPORT, academicYearMatches, autoMapColumns, headingKey, matchColumns, missingRequiredFields, normalizeHeading, parseDateInput, templateRows } from "../../convex/model/importSpecs";
import { parseCsv, toCsv } from "../../src/features/imports/spreadsheet";

const TODAY = "2026-07-01";
const row = (rowNumber: number, values: Record<string, string>) => ({ rowNumber, values });

async function setup() {
  const t = makeTest();
  const A = await createSchool(t, "alpha");
  const B = await createSchool(t, "beta");
  return { t, A, B };
}

const counts = (t: T) => t.run(async (ctx) => ({
  students: (await ctx.db.query("students").collect()).length,
  enrollments: (await ctx.db.query("enrollments").collect()).length,
  contacts: (await ctx.db.query("guardians").collect()).length, // parent contacts
  links: (await ctx.db.query("guardianLinks").collect()).length,
  memberships: (await ctx.db.query("schoolMemberships").collect()).length,
  teachers: (await ctx.db.query("teachers").collect()).length,
}));

describe("student import", () => {
  test("valid rows create students, enrollments and de-duplicated parent contacts", async () => {
    const { t, A } = await setup();
    const admin = await as(t, A.users.admin);
    const rows = [
      row(2, { fullName: "Ishita Menon", className: "Grade 8", section: "A", dateOfBirth: "14/05/2013", gender: "F", parentName: "Kavita Menon", parentPhone: "+91 98450 77777", parentRelation: "Mother" }),
      row(3, { firstName: "Ravi", lastName: "Menon", className: "8", section: "a", rollNo: "7", parentName: "Kavita Menon", parentPhone: "+91 98450 77777" }),
      row(4, { fullName: "Zoya Khan", className: "grade 8", section: "8-B", admissionNo: "MANUAL-77" }),
    ];
    const preview = await admin.query(api.imports.previewStudents, { rows, createAccounts: false, today: TODAY });
    expect(preview.summary).toMatchObject({ total: 3, invalid: 0 });
    const before = await counts(t);
    const res = await admin.mutation(api.imports.commitStudentRows, { rows, createAccounts: false, today: TODAY });
    expect(res.created).toHaveLength(3);
    const after = await counts(t);
    expect(after.students - before.students).toBe(3);
    expect(after.enrollments - before.enrollments).toBe(3);
    expect(after.contacts - before.contacts).toBe(1); // siblings share one parent contact (same phone)
    expect(after.links - before.links).toBe(2);
    const stored = await t.run(async (ctx) => {
      const s = (await ctx.db.get(res.created[0].studentId))!;
      const e = await ctx.db.query("enrollments").withIndex("by_student_year", (q) => q.eq("studentId", s._id)).first();
      const ravi = await ctx.db.query("enrollments").withIndex("by_student_year", (q) => q.eq("studentId", res.created[1].studentId)).first();
      return { s, e, ravi };
    });
    expect(stored.s).toMatchObject({ schoolId: A.schoolId, firstName: "Ishita", lastName: "Menon", gender: "female", dateOfBirth: "2013-05-14", admissionDate: TODAY });
    expect(stored.s.admissionNo).toMatch(/^AL-2026-\d{4}$/); // generated by the server counter
    // Roll numbers are system-assigned to the WHOLE section alphabetically (Asha S was already in 8-A);
    // the file's rollNo "7" is ignored.
    expect(stored.e).toMatchObject({ sectionId: A.sectionA, rollNo: 2 }); // Asha 1, Ishita 2, Ravi 3
    expect(stored.ravi?.rollNo).toBe(3);
    expect(res.created[2].admissionNo).toBe("MANUAL-77");
  });

  test("missing required fields, bad dates/enums and unknown class/section are reported per row", async () => {
    const { t, A } = await setup();
    const admin = await as(t, A.users.admin);
    const { results, summary } = await admin.query(api.imports.previewStudents, {
      rows: [
        row(2, { firstName: "Only", className: "Grade 8", section: "A" }),
        row(3, { fullName: "Bad Date", className: "Grade 8", section: "A", dateOfBirth: "31/02/2012", gender: "x" }),
        row(4, { fullName: "No Class", className: "Grade 12", section: "A" }),
        row(5, { fullName: "No Section", className: "Grade 8", section: "Z" }),
        row(6, { fullName: "Future Born", className: "Grade 8", section: "A", dateOfBirth: "2030-01-01" }),
        row(7, { fullName: "Half Contact", className: "Grade 8", section: "A", parentName: "Someone" }),
      ],
      createAccounts: false, today: TODAY,
    });
    expect(summary).toMatchObject({ total: 6, invalid: 6 });
    const errs = (n: number) => results.find((r) => r.rowNumber === n)!.errors.map((e) => e.field);
    expect(errs(2)).toContain("lastName");
    expect(errs(3)).toEqual(expect.arrayContaining(["dateOfBirth", "gender"]));
    expect(errs(4)).toContain("className");
    expect(errs(5)).toContain("section");
    expect(errs(6)).toContain("dateOfBirth");
    expect(errs(7)).toContain("parentPhone");
  });

  test("duplicate admission numbers (in file and existing) are rejected; uploaded roll numbers never conflict", async () => {
    const { t, A } = await setup();
    const admin = await as(t, A.users.admin);
    const { results } = await admin.query(api.imports.previewStudents, {
      rows: [
        row(2, { fullName: "One A", className: "Grade 8", section: "A", admissionNo: "X-1" }),
        row(3, { fullName: "Two A", className: "Grade 8", section: "A", admissionNo: "x-1" }),
        row(4, { fullName: "Three A", className: "Grade 8", section: "A", admissionNo: "alpha-Asha" }),
        row(5, { fullName: "Four A", className: "Grade 8", section: "A", rollNo: "1" }),
      ],
      createAccounts: false, today: TODAY,
    });
    expect(results.find((r) => r.rowNumber === 2)!.status).not.toBe("invalid");
    expect(results.find((r) => r.rowNumber === 3)!.errors[0].message).toMatch(/repeated \(first used on row 2\)/);
    expect(results.find((r) => r.rowNumber === 4)!.errors[0].message).toMatch(/already belongs to Asha S/);
    // Roll number 1 is taken by Asha S, but file roll numbers are ignored, so this is not an error.
    expect(results.find((r) => r.rowNumber === 5)!.status).not.toBe("invalid");
  });

  test("a commit with any invalid row writes nothing", async () => {
    const { t, A } = await setup();
    const admin = await as(t, A.users.admin);
    const before = await counts(t);
    const code = await errorCode(admin.mutation(api.imports.commitStudentRows, {
      rows: [
        row(2, { fullName: "Valid Kid", className: "Grade 8", section: "A", parentName: "G", parentPhone: "9876543210" }),
        row(3, { fullName: "Broken Kid", className: "Nope", section: "A" }),
      ],
      createAccounts: true, today: TODAY,
    }));
    expect(code).toBe("INVALID_ARGUMENT");
    expect(await counts(t)).toEqual(before);
  });

  test("duplicate Login IDs (in file and existing) are rejected; accounts are reserved then issued", async () => {
    const { t, A } = await setup();
    const admin = await as(t, A.users.admin);
    await admin.action(api.accounts.create, { person: { kind: "student", studentId: A.studentB }, loginId: "TAKEN-1" });
    const { results } = await admin.query(api.imports.previewStudents, {
      rows: [
        row(2, { fullName: "L One", className: "Grade 8", section: "A", loginId: "new-1" }),
        row(3, { fullName: "L Two", className: "Grade 8", section: "A", loginId: "NEW-1" }),
        row(4, { fullName: "L Three", className: "Grade 8", section: "A", loginId: "taken-1" }),
        row(5, { fullName: "L Four", className: "Grade 8", section: "A", loginId: "no spaces!" }),
      ],
      createAccounts: true, today: TODAY,
    });
    expect(results.map((r) => r.status)).toEqual(["valid", "invalid", "invalid", "invalid"]);

    const res = await admin.mutation(api.imports.commitStudentRows, {
      rows: [row(2, { fullName: "L One", className: "Grade 8", section: "A", loginId: "new-1" }), row(3, { fullName: "L Two", className: "Grade 8", section: "A" })],
      createAccounts: true, today: TODAY,
    });
    expect(res.created.map((c) => c.loginId)).toEqual(["NEW-1", expect.stringMatching(/^STU-2026-\d{5}$/)]);
    // Reserved accounts are pending (no identity) until credentials are issued.
    const pending = await t.run((ctx) => Promise.all(res.created.map((c) => ctx.db.get(c.membershipId!))));
    expect(pending.every((m) => m!.status === "invited" && !m!.userId && m!.studentId)).toBe(true);
    const issued = await admin.action(api.accounts.issuePendingCredentials, { targetMembershipIds: res.created.map((c) => c.membershipId!) });
    expect(issued.every((x) => x.ok)).toBe(true);
    const active = await t.run((ctx) => Promise.all(res.created.map((c) => ctx.db.get(c.membershipId!))));
    expect(active.every((m) => m!.status === "active" && m!.userId)).toBe(true);
  });

  test("unauthorized imports are rejected; account creation needs users:manage", async () => {
    const { t, A } = await setup();
    const rows = [row(2, { fullName: "Sneaky Kid", className: "Grade 8", section: "A" })];
    for (const u of [A.users.classTeacher, A.users.student]) {
      const c = await as(t, u);
      expect(await errorCode(c.query(api.imports.previewStudents, { rows, createAccounts: false, today: TODAY }))).toBe("FORBIDDEN");
      expect(await errorCode(c.mutation(api.imports.commitStudentRows, { rows, createAccounts: false, today: TODAY }))).toBe("FORBIDDEN");
    }
    // Asking for accounts additionally requires users:manage.
    expect(await errorCode((await as(t, A.users.classTeacher)).mutation(api.imports.commitStudentRows, { rows, createAccounts: true, today: TODAY }))).toBe("FORBIDDEN");
  });

  test("imports only see the caller's school (classes of another school do not resolve)", async () => {
    const { t, A, B } = await setup();
    await t.run((ctx) => ctx.db.insert("classes", { schoolId: B.schoolId, name: "Grade 9", level: 9, active: true }));
    const { results } = await (await as(t, A.users.admin)).query(api.imports.previewStudents, {
      rows: [row(2, { fullName: "Cross School", className: "Grade 9", section: "A" })], createAccounts: false, today: TODAY,
    });
    expect(results[0].errors[0].field).toBe("className");
  });

  test("row limit and malformed row numbers are rejected", async () => {
    const { t, A } = await setup();
    const admin = await as(t, A.users.admin);
    const many = Array.from({ length: 301 }, (_, i) => row(i + 2, { fullName: `Kid ${i} X`, className: "Grade 8", section: "A" }));
    expect(await errorCode(admin.query(api.imports.previewStudents, { rows: many, createAccounts: false, today: TODAY }))).toBe("INVALID_ARGUMENT");
    expect(await errorCode(admin.query(api.imports.previewStudents, { rows: [row(2, { fullName: "A B" }), row(2, { fullName: "C D" })], createAccounts: false, today: TODAY }))).toBe("INVALID_ARGUMENT");
  });
});

describe("teacher import", () => {
  test("validates subjects, employee IDs and Login IDs; creates teachers with accounts", async () => {
    const { t, A } = await setup();
    const admin = await as(t, A.users.admin);
    const { results } = await admin.query(api.imports.previewTeachers, {
      rows: [
        row(2, { fullName: "Anita Rao", subjects: "math", email: "anita@x.test" }),
        row(3, { fullName: "Bad Subject", subjects: "Astrology" }),
        row(4, { fullName: "Dup Emp", employeeId: "alpha-Class" }),
        row(5, { fullName: "Same Mail", email: "ANITA@x.test" }),
      ],
      createAccounts: true, today: TODAY,
    });
    expect(results.map((r) => r.status)).toEqual(["valid", "invalid", "invalid", "warning"]);
    const before = await counts(t);
    const res = await admin.mutation(api.imports.commitTeacherRows, {
      rows: [row(2, { fullName: "Anita Rao", subjects: "MATH; Mathematics", title: "Ms.", joiningDate: "2026-06-01" })], createAccounts: true, today: TODAY,
    });
    const after = await counts(t);
    expect(after.teachers - before.teachers).toBe(1);
    expect(after.memberships - before.memberships).toBe(1);
    const teacher = await t.run((ctx) => ctx.db.get(res.created[0].teacherId));
    expect(teacher).toMatchObject({ schoolId: A.schoolId, firstName: "Anita", lastName: "Rao", specializationSubjectIds: [A.subjectId], joiningDate: "2026-06-01" });
    expect(teacher!.employeeId).toMatch(/^AL-EMP-\d{3}$/);
    expect(res.created[0].loginId).toMatch(/^TCH-\d{5}$/);
  });

  test("teachers cannot import teachers", async () => {
    const { t, A } = await setup();
    expect(await errorCode((await as(t, A.users.classTeacher)).mutation(api.imports.commitTeacherRows, {
      rows: [row(2, { fullName: "Self Made" })], createAccounts: false, today: TODAY,
    }))).toBe("FORBIDDEN");
  });
});

describe("spreadsheet parsing (browser side, shared specs)", () => {
  test("CSV: BOM, quotes, escaped quotes, CRLF and embedded newlines", () => {
    const text = '\uFEFFName,Address,Class\r\n"Menon, Ishita","12 ""A"" Street\nJayanagar",10\r\n';
    expect(parseCsv(text)).toEqual([["Name", "Address", "Class"], ["Menon, Ishita", '12 "A" Street\nJayanagar', "10"]]);
    expect(() => parseCsv('a,"b')).toThrow(/unclosed quote/);
  });
  test("CSV export neutralises formulas (CSV injection)", () => {
    const out = toCsv([["=HYPERLINK(1)", "+1", "-2", "@x", "safe"]]);
    expect(out).toBe(`"'=HYPERLINK(1)","'+1","'-2","'@x","safe"`);
  });
  test("templates round-trip through the column auto-mapping", () => {
    const [headings] = templateRows(STUDENT_IMPORT);
    const mapping = autoMapColumns(headings, STUDENT_IMPORT);
    expect(mapping.className).not.toBeNull();
    expect(mapping.parentPhone).not.toBeNull();
    expect(autoMapColumns(["Student Name", "Std", "Div", "Adm No."], STUDENT_IMPORT)).toMatchObject({ fullName: 0, className: 1, section: 2, admissionNo: 3 });
    // Template examples are never formula-like, so the downloaded template re-imports unchanged.
    expect(templateRows(STUDENT_IMPORT)[1].every((v) => !/^[=+\-@]/.test(v))).toBe(true);
  });
  test("dates: ISO and day-first, real calendar dates only", () => {
    expect(parseDateInput("14/05/2011")).toBe("2011-05-14");
    expect(parseDateInput("2011-5-4")).toBe("2011-05-04");
    expect(parseDateInput("31/02/2011")).toBeNull();
    expect(parseDateInput("05-14-2011")).toBeNull();
  });
});

describe("column heading matching", () => {
  const field = (heading: string) => matchColumns([heading], STUDENT_IMPORT).columns[0];
  test("camelCase, snake_case, spacing and capitalisation variants map to the same field", () => {
    const expected: Record<string, string[]> = {
      admissionNo: ["admissionNo", "admission_no", "Admission Number", "Admission No", "ADMISSION NO."],
      firstName: ["firstName", "first_name", "First Name", "  first   NAME "],
      lastName: ["lastName", "last_name", "Last Name"],
      className: ["className", "class_name", "Class"],
      section: ["sectionName", "section_name", "Section"],
      dateOfBirth: ["dateOfBirth", "date_of_birth", "Date of Birth", "DOB"],
      admissionDate: ["admissionDate", "admission_date", "Admission Date"],
      parentName: ["guardianName", "guardian_name", "Guardian Name"],
      parentPhone: ["guardianPhone", "guardian_phone", "Guardian Phone"],
      parentEmail: ["guardianEmail", "guardian_email", "Guardian Email", "Parent Email"],
      parentRelation: ["guardianRelationship", "guardian_relationship", "Guardian Relation"],
      academicYear: ["academicYear", "Academic Year"],
      gender: ["gender", "Sex"], email: ["email"], phone: ["phone"], address: ["address"], loginId: ["loginId", "Login ID"],
    };
    for (const [key, headings] of Object.entries(expected)) {
      for (const h of headings) expect([h, field(h).field, field(h).status]).toEqual([h, key, "mapped"]);
    }
    expect(normalizeHeading("guardianRelationship")).toBe("guardian relationship");
    expect(headingKey("Admission No.")).toBe(headingKey("admission_no"));
  });

  test("no fuzzy guesses: unknown, ambiguous and duplicate columns stay unmapped with a reason", () => {
    expect(field("Studnt Nme").status).toBe("unrecognized");
    expect(field("bloodGroup")).toMatchObject({ status: "not_imported", field: null });
    for (const h of ["rollNo", "roll_no", "Roll Number", "rollNumber", "roll_number", "Roll No."]) {
      expect([h, field(h).status, field(h).note]).toEqual([h, "not_imported", expect.stringMatching(/assigned automatically based on the complete class roster/)]);
    }
    const dup = matchColumns(["Phone", "Mobile", "First Name", "Last Name", "Class", "Section"], STUDENT_IMPORT);
    expect(dup.mapping.phone).toBeNull();
    expect(dup.columns.slice(0, 2).map((c) => c.status)).toEqual(["duplicate", "duplicate"]);
    expect(missingRequiredFields(dup.mapping, STUDENT_IMPORT)).toEqual([]);
    expect(missingRequiredFields(matchColumns(["First Name", "Class"], STUDENT_IMPORT).mapping, STUDENT_IMPORT)).toEqual(["Full name (or First name + Last name)", "Section"]);
  });

  test("no heading belongs to two fields of the same import (aliases stay unambiguous)", () => {
    for (const spec of [STUDENT_IMPORT, TEACHER_IMPORT]) {
      const owner = new Map<string, string>();
      for (const f of spec.fields) {
        for (const k of new Set([f.label, f.key, ...f.aliases].map(headingKey))) {
          expect(owner.get(k) ?? f.key, `${spec.target}: "${k}"`).toBe(f.key);
          owner.set(k, f.key);
        }
      }
    }
  });

  test("academic year labels", () => {
    const year = { name: "2026–27", startDate: "2026-04-01", endDate: "2027-03-31" };
    for (const ok of ["2026-27", "2026–27", "2026 - 2027", "2026/27", "2026"]) expect([ok, academicYearMatches(ok, year)]).toEqual([ok, true]);
    for (const bad of ["2025-26", "2026-28", "26-27", "next year"]) expect([bad, academicYearMatches(bad, year)]).toEqual([bad, false]);
  });
});
