/**
 * Selective distribution: build a standalone product containing Core plus the
 * selected modules only — no code, schema tables, routes or Convex functions
 * of any other module, and no internal demo layer (D4).
 *
 *   npx tsx scripts/distribute.ts <out-dir> students attendance [--skip-build]
 *   npx tsx scripts/distribute.ts <out-dir> all            (every module)
 *
 * Steps
 *  1. Resolve the selection (requirements are reported, never added) and
 *     refuse while any blocker or transitional (mixed-owner) file remains.
 *  2. Copy root configuration, public/ and every src/ + convex/ file owned by
 *     Core or a selected module (ownership map, scripts/modularity/ownership.ts).
 *     Never copied: .git, .env*, tests, scripts, docs, other modules, demo.
 *  3. Write the composition roots for the selection: provider registry, crons,
 *     schema (selected owners' tables only), demo stubs, frontend manifest and
 *     UI-contribution registries, and convex/_generated/api.d.ts.
 *  4. Prune package.json scripts that refer to files not shipped.
 *  5. Verify: owner scan of every shipped file, forbidden-reference scan
 *     (imports, api paths, table names, routes), Convex + app typecheck,
 *     route coverage, and `next build` (unless --skip-build).
 *  6. Write distribution-report.json / .md into the output directory.
 *
 * Nothing is deployed and nothing touches the source repository or any
 * Convex deployment; node_modules is linked (junction), not copied.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { ownerOf, TABLE_OWNER, type Owner } from "./modularity/ownership";
import { BUSINESS_MODULES, inclusionPlan, resolveClosure, type BusinessModule } from "./modularity/select";
import { violationKey } from "./modularity/boundaries";
import { core } from "./modularity/manifests/core";
import { MANIFESTS } from "./modularity/manifests/modules";

const ROOT = resolve(__dirname, "..");
const ROOT_FILES = ["package.json", "package-lock.json", "tsconfig.json", "next.config.ts", "next-env.d.ts", "postcss.config.js", "tailwind.config.ts", "convex.json", "components.json"];

/** Provider sets per module (convex/model/*), as imported by convex/registry.generated.ts. */
const PROVIDER_SETS: Record<BusinessModule, { file: string; names: string[] }> = {
  students: { file: "./model/studentProviders", names: ["studentsProviders"] },
  attendance: { file: "./model/attendanceRecords", names: ["attendanceProviders", "attendanceOverviewProviders"] },
  academics: { file: "./model/academicsRecords", names: ["academicsProviders"] },
  fees: { file: "./model/feeRecords", names: ["feesProviders", "feesOverviewProviders"] },
  examinations: { file: "./model/examRecords", names: ["examinationsProviders", "examinationsOverviewProviders"] },
};
const UI_SETS: Record<BusinessModule, string> = { students: "studentsUi", attendance: "attendanceUi", academics: "academicsUi", fees: "feesUi", examinations: "examinationsUi" };

type Check = { name: string; ok: boolean; detail: string };

function walk(dir: string, skip: (rel: string) => boolean): string[] {
  const out: string[] = [];
  const go = (d: string) => {
    if (!existsSync(d)) return;
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      const rel = relative(ROOT, p).replace(/\\/g, "/");
      if (skip(rel)) continue;
      if (e.isDirectory()) go(p);
      else out.push(rel);
    }
  };
  go(dir);
  return out;
}

function copy(rel: string, out: string) {
  const to = join(out, rel);
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(join(ROOT, rel), to);
}

function write(out: string, rel: string, text: string) {
  const to = join(out, rel);
  mkdirSync(dirname(to), { recursive: true });
  writeFileSync(to, text);
}

function run(cmd: string, args: string[], cwd: string, env: Record<string, string> = {}): { ok: boolean; output: string } {
  const r = spawnSync(cmd, args, { cwd, encoding: "utf8", shell: process.platform === "win32", env: { ...process.env, ...env }, maxBuffer: 64 * 1024 * 1024 });
  return { ok: r.status === 0, output: `${r.stdout ?? ""}${r.stderr ?? ""}`.trim() };
}

// ------------------------------------------------------------------ composition roots
function providerRegistry(modules: BusinessModule[]): string {
  const imports = modules.map((m) => `import { ${PROVIDER_SETS[m].names.join(", ")} } from "${PROVIDER_SETS[m].file}";`).join("\n");
  const spreads = modules.flatMap((m) => PROVIDER_SETS[m].names).map((n) => `    ...${n},`).join("\n");
  return `/**
 * GENERATED by scripts/distribute.ts — composition root for this product: ${modules.join(" + ")}.
 * Only Core reads it, via convex/core/registry.ts.
 */
import type { ModuleId } from "./contracts/manifest";
import type { ProviderRegistry } from "./contracts/providers";
${imports}

export const SELECTED_MODULES: readonly ModuleId[] = ${JSON.stringify(modules)};

/** Built on first use (provider files import Core, which imports this file). */
let built: ProviderRegistry | null = null;
export function providers(): ProviderRegistry {
  return (built ??= {
${spreads}
  });
}
`;
}

function cronsFile(modules: BusinessModule[]): string {
  const crons = [...core.crons, ...MANIFESTS.filter((m) => modules.includes(m.id)).flatMap((m) => m.backend.crons)];
  const lines = crons.map((c) => {
    const [file, fn] = c.fn.split(":");
    return `crons.daily(${JSON.stringify(c.name)}, ${JSON.stringify(c.schedule.daily).replace(/"(\w+)":/g, "$1: ")}, internal.${file}.${fn}, {});`;
  });
  return `/**
 * GENERATED by scripts/distribute.ts — scheduled jobs of this product (${modules.join(" + ")}).
 */
import { cronJobs } from "convex/server";
${crons.length ? 'import { internal } from "./_generated/api";\n' : ""}
const crons = cronJobs();
${lines.join("\n")}
export default crons;
`;
}

/** convex/schema.ts with only the tables owned by Core and the selected modules. */
function schemaFile(shipped: Set<string>): { text: string; dropped: string[]; kept: string[] } {
  const src = readFileSync(join(ROOT, "convex/schema.ts"), "utf8");
  const starts = [...src.matchAll(/^\s{2}(\w+):\s*defineTable\(/gm)].map((m) => ({ table: m[1], at: m.index ?? 0 }));
  const end = src.lastIndexOf("});");
  const head = src.slice(0, starts[0].at);
  const kept: string[] = [];
  const dropped: string[] = [];
  let body = "";
  starts.forEach((s, i) => {
    const block = src.slice(s.at, starts[i + 1]?.at ?? end);
    if (shipped.has(TABLE_OWNER[s.table] ?? "")) { kept.push(s.table); body += block; }
    else dropped.push(s.table);
  });
  return { text: `${head.replace(/^/, "// GENERATED by scripts/distribute.ts: tables of Core and the selected modules only.\n")}${body}${src.slice(end)}`, dropped, kept };
}

function apiDts(out: string): string {
  const mods = walkOut(join(out, "convex")).filter((f) => /\.ts$/.test(f) && !f.startsWith("_generated/") && !f.endsWith(".d.ts")).map((f) => f.replace(/\.ts$/, "")).sort();
  const id = (m: string) => m.replace(/[/.-]/g, "_");
  const key = (m: string) => (/^[A-Za-z_$][\w$]*$/.test(m) ? m : JSON.stringify(m));
  return `/* eslint-disable */
/**
 * Generated \`api\` utility (scripts/distribute.ts, same shape as \`convex codegen\`).
 * @module
 */

${mods.map((m) => `import type * as ${id(m)} from "../${m}.js";`).join("\n")}

import type {
  ApiFromModules,
  FilterApi,
  FunctionReference,
} from "convex/server";

declare const fullApi: ApiFromModules<{
${mods.map((m) => `  ${key(m)}: typeof ${id(m)};`).join("\n")}
}>;

export declare const api: FilterApi<
  typeof fullApi,
  FunctionReference<any, "public">
>;

export declare const internal: FilterApi<
  typeof fullApi,
  FunctionReference<any, "internal">
>;

export declare const components: {};
`;
}

function walkOut(dir: string): string[] {
  const out: string[] = [];
  const go = (d: string, prefix: string) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const rel = prefix ? `${prefix}/${e.name}` : e.name;
      if (e.isDirectory()) go(join(d, e.name), rel);
      else out.push(rel);
    }
  };
  go(dir, "");
  return out;
}

// ------------------------------------------------------------------ main
function main() {
  const args = process.argv.slice(2);
  const outArg = args.find((a) => !a.startsWith("--"));
  const requested = args.filter((a) => !a.startsWith("--")).slice(1);
  const selection = requested.length === 1 && requested[0] === "all" ? [...BUSINESS_MODULES] : requested; // "all": every module
  const skipBuild = args.includes("--skip-build");
  if (!outArg || selection.length === 0) throw new Error("Usage: npx tsx scripts/distribute.ts <out-dir> <module> [<module>…] [--skip-build]");
  const out = resolve(outArg);
  if (out === ROOT || out.startsWith(ROOT + "\\") || out.startsWith(ROOT + "/")) throw new Error("The output directory must be outside the repository.");

  // 1. selection and readiness
  const { modules, problems } = resolveClosure(selection);
  if (problems.length) throw new Error(problems.map((p) => p.detail).join("\n"));
  const plan = inclusionPlan(ROOT, modules);
  if (plan.blockers.length) throw new Error(`Export refused: ${plan.blockers.length} blocker(s):\n${plan.blockers.map(violationKey).join("\n")}`);
  if (plan.transitional.length) throw new Error(`Export refused: transitional files must be split first:\n${plan.transitional.join("\n")}`);
  const shipped = new Set<Owner>(["core", ...modules]);
  const excluded = plan.excludedModules;

  // 2. copy
  if (existsSync(out)) rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const copied: string[] = [];
  const notShipped: string[] = [];
  const unowned: string[] = [];
  for (const f of ROOT_FILES) if (existsSync(join(ROOT, f))) { copy(f, out); copied.push(f); }
  for (const f of walk(join(ROOT, "public"), () => false)) { copy(f, out); copied.push(f); }
  const sources = [
    ...walk(join(ROOT, "src"), () => false),
    ...walk(join(ROOT, "convex"), (rel) => rel === "convex/_generated" || rel.startsWith("convex/_generated/")),
  ];
  for (const f of sources) {
    if (f === "convex/tsconfig.json" || f === "convex/README.md") { copy(f, out); copied.push(f); continue; }
    const o = ownerOf(f);
    if (o === null) { unowned.push(f); continue; }
    if (o === "composition") continue; // regenerated below
    if (shipped.has(o)) { copy(f, out); copied.push(f); } else notShipped.push(f);
  }
  if (unowned.length) throw new Error(`Unowned files (add an ownership rule):\n${unowned.join("\n")}`);

  // 3. composition roots
  write(out, "convex/registry.generated.ts", providerRegistry(modules));
  write(out, "convex/demo.generated.ts", "/** GENERATED by scripts/distribute.ts — customer builds contain no demo seed data. */\nexport const DEMO_STUDENT_LOGIN_IDS: readonly string[] = [];\n");
  write(out, "convex/crons.ts", cronsFile(modules));
  const schema = schemaFile(new Set(shipped));
  write(out, "convex/schema.ts", schema.text);
  write(out, "src/modules/demo.generated.ts", '/** GENERATED by scripts/distribute.ts — customer builds contain no demo layer (D4). */\nimport type { DemoRuntime } from "@/lib/demo/runtime";\n\nexport const DEMO: DemoRuntime | null = null;\n');
  write(out, "src/modules/registry.generated.ts", `/** GENERATED by scripts/distribute.ts — manifests of this product: ${modules.join(" + ")}. */
import type { CoreContributions, ModuleManifest } from "../../convex/contracts/manifest";
import { core } from "./manifests/core";
${modules.map((m) => `import { ${m} } from "./manifests/${m}";`).join("\n")}

export const CORE: CoreContributions = core;
export const MODULE_MANIFESTS: readonly ModuleManifest[] = [${modules.join(", ")}];
`);
  const uiModules = modules.filter((m) => existsSync(join(ROOT, `src/modules/${m}/contributions.tsx`)));
  write(out, "src/modules/ui.generated.ts", `/** GENERATED by scripts/distribute.ts — UI contributions of this product. */
import type { ModuleUiContributions } from "@/lib/contributions/types";
${uiModules.map((m) => `import { ${UI_SETS[m]} } from "./${m}/contributions";`).join("\n")}

export const UI_CONTRIBUTIONS: readonly ModuleUiContributions[] = [${uiModules.map((m) => UI_SETS[m]).join(", ")}];
`);
  for (const f of ["dataModel.d.ts", "server.d.ts", "server.js", "api.js"]) copy(`convex/_generated/${f}`, out);
  write(out, "convex/_generated/api.d.ts", apiDts(out));

  // 4. package.json: product name and only scripts whose files ship
  const pkg = JSON.parse(readFileSync(join(out, "package.json"), "utf8"));
  pkg.name = `${pkg.name ?? "school"}-${modules.join("-")}`;
  const keptScripts: Record<string, string> = {};
  for (const [k, v] of Object.entries<string>(pkg.scripts ?? {})) {
    const files = [...v.matchAll(/\b((?:scripts|tests)\/[\w./-]+)/g)].map((m) => m[1]);
    if (/vitest|playwright|seed/.test(v)) continue;
    if (files.every((f) => existsSync(join(out, f)))) keptScripts[k] = v;
  }
  pkg.scripts = keptScripts;
  writeFileSync(join(out, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
  if (!existsSync(join(out, "node_modules"))) symlinkSync(join(ROOT, "node_modules"), join(out, "node_modules"), "junction");

  // 5. verification
  const checks: Check[] = [];
  const shippedFiles = [...walkOut(join(out, "src")).map((f) => `src/${f}`), ...walkOut(join(out, "convex")).map((f) => `convex/${f}`)];
  const wrongOwner = shippedFiles.filter((f) => !f.startsWith("convex/_generated/") && f !== "convex/tsconfig.json" && f !== "convex/README.md").filter((f) => { const o = ownerOf(f); return o !== null && o !== "composition" && !shipped.has(o); });
  checks.push({ name: "owner scan", ok: wrongOwner.length === 0, detail: wrongOwner.length ? wrongOwner.join(", ") : `${shippedFiles.length} files, all owned by core/${modules.join("/")}/composition` });
  checks.push({ name: "no secrets or VCS", ok: !existsSync(join(out, ".env.local")) && !existsSync(join(out, ".git")), detail: "no .env* and no .git in the output" });

  // Forbidden references: excluded modules' function files, tables, routes, imports, and the demo layer.
  const excludedManifests = MANIFESTS.filter((m) => excluded.includes(m.id));
  const excludedApi = excludedManifests.flatMap((m) => m.backend.functionFiles).map((f) => f.replace(/^convex\//, "").replace(/\.ts$/, ""));
  const excludedTables: string[] = excludedManifests.flatMap((m) => [...m.backend.tables]);
  const excludedRoutes = excludedManifests.flatMap((m) => m.routes.map((r) => r.path));
  const findings: string[] = [];
  const hrefNotes: string[] = [];
  for (const f of shippedFiles.filter((x) => /\.(ts|tsx)$/.test(x) && !x.startsWith("convex/_generated/"))) {
    // Code only: comment lines (docs, examples) are not references.
    const text = readFileSync(join(out, f), "utf8").split("\n").filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l)).join("\n");
    for (const a of excludedApi) if (new RegExp(`\\b(api|internal)\\.${a}\\.`).test(text)) findings.push(`${f}: api.${a}`);
    for (const t of excludedTables) if (new RegExp(`(query|insert|v\\.id)\\(\\s*["']${t}["']`).test(text)) findings.push(`${f}: table ${t}`);
    for (const m of [...text.matchAll(/from\s+["']([^"']+)["']/g)].map((x) => x[1])) {
      if (/(^|\/)lib\/(services|mock-data|store)(\/|$)|types\/domain|seedData/.test(m)) findings.push(`${f}: imports demo layer ${m}`);
    }
    for (const r of excludedRoutes) {
      const lit = r.replace(/\/\[[^\]]+\]/g, "");
      if (text.includes(`"${lit}`) || text.includes(`\`${lit}`)) hrefNotes.push(`${f}: ${lit}`);
    }
  }
  checks.push({ name: "forbidden references (api, tables, demo imports)", ok: findings.length === 0, detail: findings.length ? findings.join("\n") : `no reference to ${excluded.join(", ")} functions or tables, and no demo-layer import` });
  const pages = walkOut(join(out, "src/app")).filter((f) => f.endsWith("page.tsx")).map((f) => `src/app/${f}`).sort();
  const declared = [...core.routes, ...MANIFESTS.filter((m) => modules.includes(m.id)).flatMap((m) => m.routes)].map((r) => r.file).sort();
  checks.push({ name: "routes = Core + selected manifests", ok: JSON.stringify(pages) === JSON.stringify(declared), detail: `${pages.length} pages; excluded routes absent: ${excludedRoutes.length}` });
  checks.push({ name: "schema", ok: schema.dropped.every((t) => excludedTables.includes(t) || !TABLE_OWNER[t]), detail: `${schema.kept.length} tables kept; dropped: ${schema.dropped.join(", ")}` });

  const convexTsc = run("npx", ["tsc", "--noEmit", "-p", "convex"], out);
  checks.push({ name: "Convex typecheck", ok: convexTsc.ok, detail: convexTsc.output.slice(0, 4000) || "clean" });
  const appTsc = run("npx", ["tsc", "--noEmit", "-p", "."], out);
  checks.push({ name: "App typecheck", ok: appTsc.ok, detail: appTsc.output.slice(0, 4000) || "clean" });
  if (!skipBuild) {
    // node_modules is a junction to the source checkout; Turbopack only follows links inside its root,
    // so the verification build widens the root to the common parent and the shipped config is restored after.
    const configPath = join(out, "next.config.ts");
    const shippedConfig = readFileSync(configPath, "utf8");
    let common = dirname(out);
    while (!ROOT.startsWith(common)) common = dirname(common);
    writeFileSync(configPath, shippedConfig.replace("const nextConfig: NextConfig = {", `const nextConfig: NextConfig = {\n  turbopack: { root: ${JSON.stringify(common)} }, // verification build only (linked node_modules)`));
    const build = run("npx", ["next", "build"], out, { NEXT_PUBLIC_CONVEX_URL: "https://example-export-check.convex.cloud", NEXT_TELEMETRY_DISABLED: "1" });
    writeFileSync(configPath, shippedConfig);
    const built = existsSync(join(out, ".next/server/app")) ? walkOut(join(out, ".next/server/app")).filter((f) => f.endsWith(".html") || f.endsWith("page.js")) : [];
    const leaked = built.filter((f) => excludedRoutes.some((r) => f.startsWith(r.replace(/^\//, "").replace(/\/\[[^\]]+\]/g, "") + "/") || f.startsWith(r.replace(/^\//, "") + ".")));
    checks.push({ name: "next build", ok: build.ok, detail: build.ok ? `built ${built.length} route artifacts` : build.output.slice(-4000) });
    checks.push({ name: "built routes exclude other modules", ok: build.ok && leaked.length === 0, detail: leaked.length ? leaked.join(", ") : "no route artifact for an excluded module" });
  }

  // 6. report
  const report = {
    product: modules, excludedModules: excluded, output: out, generatedAt: new Date().toISOString(),
    files: { shipped: copied.length, notShipped: notShipped.length },
    schema: { kept: schema.kept, dropped: schema.dropped },
    packageScripts: Object.keys(keptScripts),
    checks,
    notes: { hrefLiteralsToAbsentRoutes: hrefNotes },
  };
  writeFileSync(join(out, "distribution-report.json"), JSON.stringify(report, null, 2) + "\n");
  const md = [`# Distribution: ${modules.join(" + ")}`, "", `Excluded: ${excluded.join(", ")}`, "", "| Check | Result |", "|---|---|",
    ...checks.map((c) => `| ${c.name} | ${c.ok ? "PASS" : "FAIL"} |`), "", ...checks.filter((c) => !c.ok).map((c) => `## ${c.name}\n\n\`\`\`\n${c.detail}\n\`\`\``)].join("\n");
  writeFileSync(join(out, "distribution-report.md"), md + "\n");
  for (const c of checks) console.log(`${c.ok ? "PASS" : "FAIL"}  ${c.name}${c.ok ? ` — ${c.detail.split("\n")[0]}` : ""}`);
  if (hrefNotes.length) console.log(`note: ${hrefNotes.length} href literal(s) to absent routes, all behind isRouteShipped/module checks (see report)`);
  if (checks.some((c) => !c.ok)) { console.log(`\nFailures written to ${join(out, "distribution-report.md")}`); process.exitCode = 1; }
  void statSync;
}

main();
